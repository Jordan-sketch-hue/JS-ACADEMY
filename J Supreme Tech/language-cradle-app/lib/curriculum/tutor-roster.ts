/** Tutors with an AI-generated portrait photo (_build/gen-tutor-portraits.mjs).
 *  Excludes en-gooden — she's a real person, never AI-generate her likeness. */
const HAS_PORTRAIT = new Set(
  Object.values(LANGUAGE_TUTORS)
    .flat()
    .map((t) => t.id)
    .filter((id) => id !== "en-gooden"),
);

/** Best available face for a tutor: portrait JPG if generated, else the SVG mark. */
export function tutorFaceUrl(id: string): { url: string; isPhoto: boolean } {
  if (HAS_PORTRAIT.has(id)) return { url: `/avatars/${id}.jpg`, isPhoto: true };
  return { url: tutorAvatarUrl(id), isPhoto: false };
}

const two = (lang?: string) => (lang ?? "en").slice(0, 2).toLowerCase();

/** All selectable tutors for a language (BCP-47 or 2-letter). */
export function rosterForLang(lang?: string): RosterTutor[] {
  return LANGUAGE_TUTORS[two(lang)] ?? LANGUAGE_TUTORS.en;
}

/** Find a tutor by its voice id (across all languages). */
export function tutorByVoiceId(voiceId: string): RosterTutor | undefined {
  for (const list of Object.values(LANGUAGE_TUTORS)) {
    const t = list.find((x) => x.voiceId === voiceId);
    if (t) return t;
  }
  return undefined;
}

/** Find a tutor by id. */
export function tutorById(id: string): RosterTutor | undefined {
  for (const list of Object.values(LANGUAGE_TUTORS)) {
    const t = list.find((x) => x.id === id);
    if (t) return t;
  }
  return undefined;
}
