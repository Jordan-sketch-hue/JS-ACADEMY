/* ============================================================
 *  TUTOR ROSTER · multiple selectable native tutors per language
 *
 *  Each language offers several native-speaker AI tutors (distinct
 *  Azure neural voices). Students pick their tutor; the lesson plays
 *  in that tutor's voice. The first entry per language is the default
 *  (matches lib/curriculum/instructors.ts primary tutor).
 *
 *  Voice ids are Azure neural names — providerForVoiceId() routes them
 *  to Azure automatically (no voice-cast.json entry required).
 * ============================================================ */

export type RosterTutor = {
  /** Stable id — used in localStorage + demo filenames. */
  id: string;
  name: string;
  /** Azure neural voice. */
  voiceId: string;
  gender: "male" | "female";
  /** Human accent/region label. */
  accent: string;
  blurb: string;
  /** Shown but NOT selectable yet (e.g. Dr. Gooden's real cloned voice). */
  comingSoon?: boolean;
};

/** Illustrated avatar mark for a tutor — generated by _build/gen-tutor-avatars.mjs. */
export function tutorAvatarUrl(id: string): string {
  return `/avatars/${id}.svg`;
}

